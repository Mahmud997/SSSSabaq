# runtime overrides from admin (optional)
_RUNTIME_SUBJECT = {}
_RUNTIME_BASE = ""


def set_runtime_prompts(base: str | None = None, subjects: dict | None = None):
    global _RUNTIME_BASE, _RUNTIME_SUBJECT
    if base is not None:
        _RUNTIME_BASE = base
    if subjects is not None:
        _RUNTIME_SUBJECT = dict(subjects)


def build_system_prompt(subject: str, modifier: str = "") -> str:
    base = _RUNTIME_BASE.strip() if _RUNTIME_BASE else BASE_SYSTEM_PROMPT
    profiles = {**SUBJECT_PROMPTS_DEFAULT, **_RUNTIME_SUBJECT}
    profile = profiles.get(subject.strip().lower(), "Учитывай специфику предмета и возраст учащихся; не допускай фактических ошибок.")
    return base + "\nПРЕДМЕТНЫЙ ПРОФИЛЬ: " + profile + "\nМЕТОДИЧЕСКИЙ АКЦЕНТ: " + (modifier or "Не задан")
