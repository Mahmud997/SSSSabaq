def _lang_label(language: str) -> str:
    code = language_code(language)
    if not code:
        raise ValueError("Уточните язык документа")
    return LANG_LABELS[code]


def build_planning_prompts(kind: str, data: dict, context: str = ""):
    if kind not in PLAN_TYPES:
        raise ValueError("Неизвестный тип плана / оценивания")
    for key, label in (("subject", "предмет"), ("grade", "класс"), ("topic", "тема")):
        if not str(data.get(key, "")).strip():
            raise ValueError("Уточните: " + label)
    label = _lang_label(data["language"])
    hours = data.get("hours") or (34 if kind == "year_plan" else (8 if kind in ("ktp", "theme_plan") else 1))
    try:
        hours = max(1, min(140, int(hours)))
    except (TypeError, ValueError):
        hours = 8
    rules = KIND_RULES[kind].format(hours=hours)
    system = build_system_prompt(data["subject"], data.get("methodical_profile", "")) + (
        "\n\nРЕЖИМ ПЛАНИРОВАНИЯ И ОЦЕНИВАНИЯ: создай ровно один документ указанного типа. "
        "Формат — Markdown: крупные разделы «## Название», внутри «###». "
        "Таблицы — только Markdown-таблицы. Весь текст на языке документа: " + label + "."
    )
    user = f"""ТИП ДОКУМЕНТА: {DOC_TYPES[kind]}
Предмет: {data['subject']}
Класс: {data['grade']}
Тема / раздел / период: {data['topic']}
Язык: {label}
Часов (ориентир): {hours}
Условия кабинета: {data.get('room_conditions') or 'Не указаны'}
Пожелание учителя: {(data.get('instruction') or '').strip() or 'Не указано'}

ТРЕБОВАНИЯ:
{rules}

КОНТЕКСТ (цели и темы из связанного урока/материала, если есть):
{context or '(не задан — опирайся на тему и класс)'}
"""
    return system, user


async def generate_planning(kind: str, data: dict, context: str = "") -> str:
    system, user = build_planning_prompts(kind, data, context)
    return await AIProvider.from_settings().generate(system, user)
